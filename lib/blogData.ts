/**
 * Searches local FAQ knowledge base to instantly match common queries
 * avoiding costly API calls.
 */
export function findMatchingFAQ(query: string): FAQItem | null {
  const q = query.toLowerCase().trim();
  if (!q) return null;

  // Slash commands direct matching
  if (q.startsWith('/uat')) return FAQ_ITEMS.find(f => f.id === 'faq-uat') || null;
  if (q.startsWith('/cutoff')) return FAQ_ITEMS.find(f => f.id === 'faq-cutoffs') || null;
  if (q.startsWith('/faculties')) return FAQ_ITEMS.find(f => f.id === 'faq-faculties') || null;
  if (q.startsWith('/services')) return FAQ_ITEMS.find(f => f.id === 'faq-services') || null;
  if (q.startsWith('/contacts')) return FAQ_ITEMS.find(f => f.id === 'faq-contacts') || null;
  if (q.startsWith('/analysis')) return FAQ_ITEMS.find(f => f.id === 'faq-survey') || null;

  // Direct keyword matching across FAQ_ITEMS
  for (const item of FAQ_ITEMS) {
    for (const keyword of item.keywords) {
      if (q.includes(keyword)) {
        return item;
      }
    }
  }

  return null;
}

